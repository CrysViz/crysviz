// Base URL of the symdata space-group browser; the query string just preselects
// which sections of that page are expanded (wyckoff positions open, etc.).
const SYMDATA_QUERY = 'settings=ita&theme=twilight&alt_settings=open&setting_transforms=open'
  + '&harker=closed&identity=open&details=closed&pointgroup_nav=open&symops=closed'
  + '&wyckoff=open&max_subgroups=closed&min_supergroups=closed&normalizer=closed'
  + '&k_subgroups=closed&conjugacy=open&char_real=open&char_complex=open';

/** Slug used by symdata.anyterial.se: lower-cased Hall symbol, spaces -> "_".
 *  Everything else (`-`, `*`, `"`, parentheses) is kept as-is and percent-encoded. */
export function hallSlug(hallSymbol) {
  return encodeURIComponent(String(hallSymbol).toLowerCase().replace(/ /g, '_'))
    .replace(/%2F/gi, '/');
}

/** Entry for a moyo `hall_number`, or null when out of range. */
export function hallEntry(hallNumber) {
  const row = HALL_SYMBOLS[hallNumber - 1];
  if (!row) return null;
  return { symbol: row[0], number: row[1], hm: row[2], choice: row[3] };
}

/** Page on symdata.anyterial.se for a Hall symbol (Wyckoff positions section). */
export function symdataHallUrl(hallSymbol) {
  return `https://symdata.anyterial.se/hall/${hallSlug(hallSymbol)}/?${SYMDATA_QUERY}#wyckoff-positions`;
}
