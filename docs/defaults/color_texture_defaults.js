export function getViridisColors(nBins = 100) {
  const stops = [
    { t: 0.0, r: 68, g: 1, b: 84 },
    { t: 0.1, r: 72, g: 33, b: 116 },
    { t: 0.2, r: 69, g: 67, b: 147 },
    { t: 0.3, r: 59, g: 82, b: 139 },
    { t: 0.4, r: 44, g: 101, b: 142 },
    { t: 0.5, r: 33, g: 123, b: 140 },
    { t: 0.6, r: 29, g: 145, b: 123 },
    { t: 0.7, r: 34, g: 168, b: 103 },
    { t: 0.8, r: 60, g: 189, b: 74 },
    { t: 0.9, r: 136, g: 204, b: 57 },
    { t: 1.0, r: 222, g: 217, b: 38 },
  ];
  const colors = [];
  for (let i = 0; i < nBins; i++) {
    const t = i / (nBins - 1);

    // Find the two stops surrounding `t`
    let stop1, stop2;
    for (let j = 0; j < stops.length - 1; j++) {
      if (t >=  stops[j].t && t <= stops[j + 1].t) {
        stop1 = stops[j];
        stop2 = stops[j + 1];
        break;
      }
    }

    // Linearly interpolate RGB
    const localT = (t - stop1.t) / (stop2.t - stop1.t);
    const r = (stop1.r + (stop2.r - stop1.r) * localT) / 255;
    const g = (stop1.g + (stop2.g - stop1.g) * localT) / 255;
    const b = (stop1.b + (stop2.b - stop1.b) * localT) / 255;

    colors.push(new THREE.Color(r, g, b));
  }

  return colors;

}

