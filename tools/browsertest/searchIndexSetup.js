// Shared by gen_search_index.js (writes docs/ui/search/controlIndex.js) and
// tests/searchindex.test.js (proves the committed file is current): put the
// app into the state the feature search's control list is harvested from,
// and build that list. Both MUST go through here — a different state would
// harvest a different list and the test would fail on a fresh index.
//
// State: the default boot structure, plus a small synthetic OUTCAR (a
// four-step trajectory with forces and stress) loaded and selected, so the
// trajectory-bound windows (Trajectory, Lattice Analysis) and Forces are
// available and get indexed; Show Polyhedra on, so the Polyhedra window is.
'use strict';

const STEP = (lat, toten, fx, pkb) => [
  '  direct lattice vectors                 reciprocal lattice vectors',
  ...lat.map((row) => `     ${row.map((v) => v.toFixed(9)).join('  ')}     0.250000000  0.000000000  0.000000000`),
  '',
  ' POSITION                                       TOTAL-FORCE (eV/Angst)',
  ' -----------------------------------------------------------------------------------',
  '      0.00000      0.00000      0.00000         0.000000      0.000000      0.000000',
  `      2.00000      0.00000      0.00000         ${fx.toFixed(6)}      0.000000      0.000000`,
  ' -----------------------------------------------------------------------------------',
  '    total drift:                                0.000000      0.000000      0.000000',
  '',
  `  in kB      ${pkb.toFixed(2)}     ${pkb.toFixed(2)}     ${pkb.toFixed(2)}      0.00      0.00      0.00`,
  '',
  '  FREE ENERGIE OF THE ION-ELECTRON SYSTEM (eV)',
  '  ---------------------------------------------------',
  `  free  energy   TOTEN  =      ${toten.toFixed(8)} eV`,
  '',
];
const HEADER = [
  ' vasp.6.4.2 20Jul23 complex',
  ' POTCAR:    PAW_PBE Na_pv 19Sep2006',
  ' POTCAR:    PAW_PBE Cl 06Sep2000',
  '   ions per type =               1   1',
  '',
];
const LATTICES = [
  [[4.0, 0, 0], [0, 4.0, 0], [0, 0, 4.0]],
  [[4.1, 0, 0], [0, 4.1, 0], [0, 0, 4.1]],
  [[4.2, 0, 0], [0, 4.2, 0], [0, 0, 4.4]],
  [[4.2, 0, 0], [0.4, 4.2, 0], [0, 0, 4.4]],
];
const OUTCAR = [...HEADER, ...LATTICES.flatMap((lat, i) => STEP(lat, -10 - i, -0.1 * (i + 1), 100 * (i + 1)))].join('\n');

/** Load the fixture, then harvest. Returns the serialized index body. */
async function buildSearchIndex(page) {
  await page.evaluate(async (outcar) => {
    const cv = await import('./core/crystal-viewer.js');
    await cv.loadStructure(outcar, 'OUTCAR_search_index');
  }, OUTCAR);
  await page.waitForTimeout(2500);
  await page.evaluate(() => {
    const cb = /** @type {HTMLInputElement} */ (document.getElementById('showPolyhedra'));
    if (cb && !cb.checked) {
      cb.checked = true;
      cb.dispatchEvent(new Event('change', { bubbles: true }));
    }
  });
  await page.waitForTimeout(1500);
  return page.evaluate(async () => {
    const b = await import('./ui/search/indexBuilder.js');
    return b.serializeControlIndex(await b.buildControlIndex());
  });
}

const INDEX_HEADER = `// GENERATED by tools/browsertest/gen_search_index.js (make search-index).
// Do not edit by hand: change the window, then regenerate. The searchindex
// browser test fails while this file is stale.
//
// The full list of controls the feature search (ui/FeatureSearch.js) can take
// the user to, harvested by ui/search/indexBuilder.js from every window with
// every tab walked — so windows that are folded, never opened, or still in
// the Feature Store are searchable too. Each entry: the window (panel id),
// the control's label, the section headline above it, its kind, its element
// id when it has a stable one, and the in-window tabs to select first.
`;

function renderIndexFile(body) {
  return `${INDEX_HEADER}\nexport const CONTROL_INDEX = [\n${body}\n];\n`;
}

module.exports = { buildSearchIndex, renderIndexFile, OUTCAR };
